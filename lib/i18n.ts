export type Key = keyof typeof en;

export type TFn = (key: Key, vars?: Record<string, string | number>) => string;

const DICTIONARIES: Record<Lang, Record<Key, string>> = { en, bm };

export function interpolate(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in vars ? String(vars[name]) : match,
  );
}

export function translator(lang: Lang): TFn {
  return (key, vars): string =>
    interpolate(DICTIONARIES[lang][key] ?? DICTIONARIES.en[key] ?? key, vars);
}
